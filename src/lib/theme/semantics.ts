// NOON WAS CALLED EXHIBITION BEFORE UI-P02. Same theme, same values; only the
// name changed. A preference stored under the old name is migrated to "noon" by
// the boot script in index.html and by ThemeContext.
//
// A semantic token names a *job*. This is the only table a component's colours
// come from, and a component touches it through `tokens.ts` (`t.module`), never
// through these objects directly: a resolved value does not follow the theme
// attribute, a `var(--module)` does.
//
// `noon` and `dusk` are light and dark modes of one product, not two brands: same
// token names, same jobs, only the values differ. Every name in TOKEN_NAMES
// appears in both objects, which `Record<TokenName,…>` enforces at compile time.
// Adding a token means adding it to TOKEN_NAMES, to both objects, and to both
// theme blocks in `src/index.css`; `css-parity.test.ts` holds the three together.
//
// THE VALUES ARE THE REFINED BOARDS' (`design/reference/refined/{dusk,noon}`;
// UI-P79 to UI-P97), and since UI-P99 the only ones: the palette that stood
// behind them in `primitives.ts` went with the look it served. Use a token only
// in its role. If a surface needs a colour no token names, add the token; never
// borrow one because its value happens to be right today.
//
// `--recess` IS A SURFACE AND NEVER INK (BG-P30). It is one step from `--bg` by
// design, so ink painted with it is nearly invisible. The token for quiet ink is
// `--text2`. If a state needs to be quieter than that, it is quieter than
// legible, and the answer is weight or size, not a paler colour.
//
// The nine category hues, a tenth fallback and a chip fill for each of the ten
// (BG-P05) are spent only through `category.ts`.

