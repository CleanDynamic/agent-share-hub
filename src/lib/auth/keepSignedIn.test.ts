// G13: "Keep me signed in" decides where the session is kept. Ticked: localStorage, which outlives the browser.
// Unticked: sessionStorage, which the browser clears when it closes. Proven by reading where the session lands.

import { readFileSync } from "node:fs";
import { beforeEach, describe, expect, it } from "vitest";

import { KEEP_SIGNED_IN_KEY, keepSignedIn, keepSignedInStorage, setKeepSignedIn } from "./keepSignedIn";

const KEY = "sb-test-auth-token";
const SESSION = JSON.stringify({ access_token: "a", refresh_token: "r" });

beforeEach(() => {
  localStorage.clear();
  sessionStorage.clear();
});

describe("keepSignedInStorage", () => {
  it("is ticked by default, so nobody's behaviour changes unless they untick it (D6)", () => {
    expect(keepSignedIn()).toBe(true);
    const storage = keepSignedInStorage(localStorage)!;
    storage.setItem(KEY, SESSION);
    expect(localStorage.getItem(KEY)).toBe(SESSION);
    expect(sessionStorage.getItem(KEY)).toBeNull();
  });

  it("ticked: the session is kept in persistent storage", () => {
    setKeepSignedIn(true);
    keepSignedInStorage(localStorage)!.setItem(KEY, SESSION);
    expect(localStorage.getItem(KEY)).toBe(SESSION);
    expect(sessionStorage.getItem(KEY)).toBeNull();
  });

  it("unticked: the session is kept for this browser session only, never in persistent storage", () => {
    setKeepSignedIn(false);
    const storage = keepSignedInStorage(localStorage)!;
    storage.setItem(KEY, SESSION);
    expect(sessionStorage.getItem(KEY)).toBe(SESSION);
    expect(localStorage.getItem(KEY)).toBeNull();
    expect(storage.getItem(KEY)).toBe(SESSION);
  });

  it("unticked after a kept session: the refreshed session moves out of persistent storage", () => {
    setKeepSignedIn(true);
    const storage = keepSignedInStorage(localStorage)!;
    storage.setItem(KEY, SESSION);
    setKeepSignedIn(false);
    storage.setItem(KEY, SESSION);
    expect(localStorage.getItem(KEY)).toBeNull();
    expect(sessionStorage.getItem(KEY)).toBe(SESSION);
  });

  it("signing out removes the session from both", () => {
    localStorage.setItem(KEY, SESSION);
    sessionStorage.setItem(KEY, SESSION);
    keepSignedInStorage(localStorage)!.removeItem(KEY);
    expect(localStorage.getItem(KEY)).toBeNull();
    expect(sessionStorage.getItem(KEY)).toBeNull();
  });

  it("stores only the choice, never the session, under its own key", () => {
    setKeepSignedIn(false);
    expect(localStorage.getItem(KEEP_SIGNED_IN_KEY)).toBe("0");
    setKeepSignedIn(true);
    expect(localStorage.getItem(KEEP_SIGNED_IN_KEY)).toBeNull();
  });

  it("leaves the Lovable preview broker as it is", () => {
    const broker = { getItem: () => null, setItem: () => undefined, removeItem: () => undefined };
    expect(keepSignedInStorage(broker)).toBe(broker);
    expect(keepSignedInStorage(undefined)).toBeUndefined();
  });
});

describe("the client uses it (a guard: client.ts is regenerated by tools and this line must survive)", () => {
  it("passes the broker through keepSignedInStorage", () => {
    const client = readFileSync("src/integrations/supabase/client.ts", "utf8");
    expect(client).toMatch(/storage:\s*keepSignedInStorage\(brokeredPreviewStorage\(\)\)/);
    expect(client).toMatch(/import \{ keepSignedInStorage \} from ["']@\/lib\/auth\/keepSignedIn["']/);
  });
});
